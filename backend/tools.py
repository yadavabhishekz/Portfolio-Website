"""
LangChain tool definitions for portfolio routing.

Each tool tells the frontend which UI card to display. The card content is
rendered entirely from static frontend data, never generated by the LLM.
The tool *result* (added to the reply call's system prompt) carries the matching
knowledge document, so the reply is grounded in the same facts the card shows.
"""

from typing import Literal

from langchain_core.tools import tool

from retriever import get_document

# Must match the `id` values of PROJECTS in frontend/src/data.js
ProjectId = Literal["budans-brew", "recap", "series-nlp", "job-recommender", "ai-data-analyst"]
PROJECT_IDS = ProjectId.__args__


def _doc_body(doc_id: str) -> str:
    doc = get_document(doc_id)
    return doc.body if doc else ""


def _card_result(card: str, notes: str = "") -> str:
    """Tool result: what's now on screen, plus private reference notes for the reply.

    The notes are framed explicitly as reference material — without that, models
    sometimes paste the whole document back as their reply.
    """
    result = (
        f"The {card} is now on screen, so the visitor can already read its details. "
        "Reply in 2-4 conversational sentences in your own words. "
        "Do NOT copy, list, or paste the reference notes."
    )
    if notes:
        result += f"\n\n<reference_notes>\n{notes}\n</reference_notes>"
    return result


def _overview(doc_id: str) -> str:
    """First section of a knowledge document (its one-paragraph summary)."""
    body = _doc_body(doc_id)
    first = body.split("\n## ")[0].removeprefix("## ")
    return first.strip()


@tool
def getProjects() -> str:
    """Use this when the user asks about projects in general, work, portfolio pieces, or things built."""
    overviews = "\n\n".join(_overview(f"project-{pid}") for pid in PROJECT_IDS)
    return _card_result("projects carousel", overviews)


@tool
def getProject(project_id: ProjectId) -> str:
    """Use this when the user asks about ONE specific project by name (e.g. RECAP, Budan's Brew,
    the series/Naruto NLP project, the job recommender, the AI data analyst / text-to-SQL)."""
    return _card_result("detail card for this project", _doc_body(f"project-{project_id}"))


@tool
def getPresentation() -> str:
    """Use this when the user asks who you are, for an introduction, or background/bio info."""
    return _card_result("about-me card", _doc_body("about"))


@tool
def getSkills() -> str:
    """Use this when the user asks about skills, technologies, or technical/soft skills."""
    return _card_result("skills card", _doc_body("skills"))


@tool
def getContact() -> str:
    """Use this when the user asks how to reach out, contact info, email, or socials."""
    return _card_result("contact card (my email, GitHub, LinkedIn, and X)")


@tool
def getExperience() -> str:
    """Use this when the user asks about work experience, where I work, my current job or employer,
    internships, or professional background."""
    return _card_result("experience card", _doc_body("experience"))


@tool
def getResume() -> str:
    """Use this when the user asks for a resume, CV, or wants to download a resume."""
    return _card_result("resume card (clicking it downloads my resume as a PDF)")


@tool
def getHowItWorks() -> str:
    """Use this when the user asks how this website/portfolio/chatbot works, how it was built,
    its architecture, or what tech powers it."""
    return _card_result("how-this-site-works card", _doc_body("this-site"))


# All available tools as a list (for bind_tools)
ALL_TOOLS = [
    getProjects, getProject, getPresentation, getSkills,
    getContact, getExperience, getResume, getHowItWorks,
]
TOOLS_BY_NAME = {t.name: t for t in ALL_TOOLS}

# Knowledge document each card is grounded in (shown to the user as the reply's source)
_TOOL_DOCS = {
    "getPresentation": "about",
    "getSkills": "skills",
    "getExperience": "experience",
    "getHowItWorks": "this-site",
}


def grounding_doc(tool_name: str, tool_args: dict):
    """The knowledge document a tool's card/result is based on, if any."""
    if tool_name == "getProject":
        return get_document(f"project-{tool_args.get('project_id')}")
    doc_id = _TOOL_DOCS.get(tool_name)
    return get_document(doc_id) if doc_id else None
